def response_origin(res):
    """Origen REAL de la respuesta, derivado del flujo ejecutado (no del contenido):
    LLM = el texto mostrado procede de la llamada de analisis del modelo; LOCAL = exito sin modelo generativo;
    ACLARACION = solicitud de aclaracion verificada; SIN_RESPUESTA = abstencion o error. MIXTA no se emite: el flujo
    actual no combina texto local con texto generado. 'modelo_consultado' indica si el modelo llego a ejecutarse
    aunque su respuesta se descartara."""
    res = res or {}
    meta = res.get("llm_meta") or {}
    prov, model = meta.get("successful_provider"), meta.get("successful_model")
    status = res.get("status")
    if status == "SUCCESS":
        tipo = "LLM" if prov else "LOCAL"
    elif status == "CLARIFICATION_REQUIRED":
        tipo = "ACLARACION"
    else:
        tipo = "SIN_RESPUESTA"
    out = {"tipo": tipo, "estado": status, "proveedor": prov, "modelo": model,
           "fallback": bool(meta.get("fallback_triggered")), "proveedor_primario": meta.get("primary_provider"),
           "modelo_consultado": bool(prov), "motivo": res.get("mode") if tipo == "SIN_RESPUESTA" else None}
    ver = (res.get("decision_integrity") or {}).get("verification")
    if isinstance(ver, dict):   # verificacion V4 (ADA_VERIFICATION_V4=1)
        out["verificacion"] = {"modo": ver.get("mode"), "modelo": (ver.get("verifier") or {}).get("model"),
                               "retirado": len(ver.get("removed") or []),
                               "excepciones_anadidas": len(ver.get("added_exceptions") or []),
                               "negativa": bool(ver.get("negative"))}
    return out


def origin_badge(origin, lang="es"):
    """(tipo, titulo, descripcion) para la interfaz."""
    t = ORIGIN_LABELS["en" if lang == "en" else "es"]
    o = origin or {}
    tipo = o.get("tipo") or "SIN_RESPUESTA"
    if tipo == "LLM":
        desc = t["llm_desc"].format(prov=o.get("proveedor") or "LLM", model=o.get("modelo") or "?")
        if o.get("fallback"):
            desc += "; " + t["fallback"].format(primary=o.get("proveedor_primario") or "?")
        v = o.get("verificacion")
        if v:
            desc += "; " + (t["v4_llm"].format(model=v.get("modelo") or "?") if v.get("modo") == "LLM" else t["v4_reduced"])
            if v.get("retirado"):
                desc += "; " + t["v4_removed"]
            if v.get("negativa"):
                desc += "; " + t["v4_negative"]
    elif tipo == "LOCAL":
        desc = t["local_desc"]
    elif tipo == "ACLARACION":
        desc = t["clar_desc"]
    else:
        desc = t["none_desc"] + (("; " + t["consulted"].format(prov=o["proveedor"])) if o.get("modelo_consultado") else "")
    return tipo, t.get(tipo, tipo), desc


def is_placeholder(text):
    return str(text or "").strip().strip(".").strip().lower() in PLACEHOLDERS


def unified_enabled(struct=None):
    """La respuesta se presenta unificada si el analisis la produjo asi o si el modo esta activo."""
    if isinstance(struct, dict) and struct.get("answer_mode") == "UNIFIED":
        return True
    return os.environ.get("ADA_UNIFIED_ANSWER", "").strip() == "1"


def unified_header(struct, lang="es"):
    t = TITLES["en" if lang == "en" else "es"]
    status = (struct or {}).get("response_status")
    return t["header_clarify"] if status == "CLARIFICATION_REQUIRED" else t["header_abstain"] if status == "ABSTAIN" else t["header"]


def unified_sections(struct, lang="es"):
    """[(campo, titulo, texto)] en orden de lectura; el summary va primero y sin titulo propio.
    En abstencion y aclaracion solo se muestra el mensaje principal y, si aporta, su motivo."""
    t = TITLES["en" if lang == "en" else "es"]
    struct = struct or {}
    out = []
    for field in UNIFIED_FIELDS:
        text = str(struct.get(field) or "").strip()
        if is_placeholder(text):
            continue
        if field == "limitations" and struct.get("response_status") in ("ABSTAIN", "CLARIFICATION_REQUIRED") \
                and text in str(struct.get("summary") or ""):
            continue  # el motivo ya figura en el mensaje principal
        out.append((field, "" if field == "summary" else t[field], text))
    return out


